/* Offline app shell for Bolo Sahayak. API and mock portal traffic stays online. */
const SHELL_CACHE = "bolo-shell-v1";
const SHELL = [
  "/",
  "/styles.css",
  "/app.js",
  "/audio.js",
  "/audio-worklet.js",
  "/packages/voice/endpointing.js",
  "/packages/voice/vad.js",
  "/packages/voice/bargein.js",
  "/manifest.webmanifest",
  "/icons/icon-192.png",
  "/icons/icon-512.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(SHELL_CACHE)
      .then((cache) => cache.addAll(SHELL))
      .then(() => self.skipWaiting())
      .catch(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== SHELL_CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // Live state belongs to the server: never serve a cached answer.
  if (url.pathname.startsWith("/v1/") || url.pathname.startsWith("/mock/")) return;
  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response && response.ok) {
          const copy = response.clone();
          caches.open(SHELL_CACHE).then((cache) => cache.put(request, copy)).catch(() => {});
        }
        return response;
      })
      .catch(() => caches.match(request).then((hit) => hit || caches.match("/")))
  );
});
